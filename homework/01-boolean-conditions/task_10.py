# ДЗ 1, задача 10 «Допуск к экзамену» (★★☆)
# Задачник, задача 2.2.11: https://python-theory-makarov.vercel.app/zadachnik/2-2/index.html#p11
#
# Студента допускают к экзамену, если посещаемость не ниже 75%, сдано не меньше 8 лабораторных
# работ и нет долга по оплате. Вводятся посещаемость в процентах, число сданных работ и сумма
# долга. Выведите результат каждой проверки и общий ответ.
#
# Каждый input() выводит подсказку. Тексты подсказок — как в примерах, после двоеточия или скобки
# стоит пробел.
#
# Пример 1
#   ввод:
#     80
#     8
#     0
#   в терминале:
#     Посещаемость, %: 80
#     Сдано лабораторных: 8
#     Долг по оплате, руб.: 0
#     Посещаемость: True
#     Лабораторные: True
#     Нет долга: True
#     Допущен: True
# Пример 2
#   ввод:
#     90
#     6
#     0
#   в терминале:
#     Посещаемость, %: 90
#     Сдано лабораторных: 6
#     Долг по оплате, руб.: 0
#     Посещаемость: True
#     Лабораторные: False
#     Нет долга: True
#     Допущен: False
# Пример 3
#   ввод:
#     75
#     10
#     1500
#   в терминале:
#     Посещаемость, %: 75
#     Сдано лабораторных: 10
#     Долг по оплате, руб.: 1500
#     Посещаемость: True
#     Лабораторные: True
#     Нет долга: False
#     Допущен: False

# Решение

exist = int(input("Посещаемость, %: "))
exam_tick = int(input("Сдано лабораторных: "))
pay = int(input("Долг по оплате, руб.: "))

if exist >= 75:
    print(f"Посещаемость: {True}")
else:
    print(f"Посещаемость: {False}")

if exam_tick >= 8:
    print(f"Сдано лабораторных: {True}")
else:
    print(f"Сдано лабораторных: {False}")

if pay > 0:
    print(f"Нет долга: {False}")
elif pay == 0:
    print(f"Нет долга: {True}")

if exist >= 75 and exam_tick >= 8 and pay == 0:
    print(f"Допущен: {True}")
else:
    print(f"Допущен: {False}")
