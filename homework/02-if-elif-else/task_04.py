# ДЗ 2, задача 4 «Интервал доставки» (★★☆)
# Главы: 2.3, 2.4
#
# Покупатель выбирает интервал доставки, например с 14 до 16 часов. Вводятся начало интервала,
# конец интервала и час, когда приехал курьер, — три целых числа. Приезд в час начала или конца
# интервала считается своевременным. Выведите «Вовремя», «Раньше интервала» или
# «Опоздание на N ч», где N — сколько часов прошло после конца интервала.
#
# Каждый input() выводит подсказку. Тексты подсказок — как в примерах, после двоеточия или скобки
# стоит пробел.
#
# Пример 1
#   ввод:
#     14
#     16
#     15
#   в терминале:
#     Начало интервала, ч: 14
#     Конец интервала, ч: 16
#     Курьер приехал, ч: 15
#     Вовремя
# Пример 2
#   ввод:
#     14
#     16
#     16
#   в терминале:
#     Начало интервала, ч: 14
#     Конец интервала, ч: 16
#     Курьер приехал, ч: 16
#     Вовремя
# Пример 3
#   ввод:
#     14
#     16
#     12
#   в терминале:
#     Начало интервала, ч: 14
#     Конец интервала, ч: 16
#     Курьер приехал, ч: 12
#     Раньше интервала
# Пример 4
#   ввод:
#     10
#     12
#     15
#   в терминале:
#     Начало интервала, ч: 10
#     Конец интервала, ч: 12
#     Курьер приехал, ч: 15
#     Опоздание на 3 ч

# Решение

interval_start = int(input("Начало интервала, ч: "))
interval_stop = int(input("Конец интервала, ч: "))
interval = int(input("Курьер приехал, ч: "))

remain = interval - interval_stop 

if interval >= interval_start and interval <= interval_stop:
    print("Вовремя")
elif interval <= interval_start and interval <= interval_stop:
    print("Раньше интервала")
elif interval >= interval_start and interval >= interval_stop:
    print(f"Опоздание на {remain} ч")
