#
# Вводится натуральное число. Выведите, сколько в нём цифр, в формате «Цифр: 4». Число не
# переводите в строку: отбрасывайте последнюю цифру делением нацело на 10.
#
# Каждый input() выводит подсказку. Тексты подсказок — как в примерах, после двоеточия или скобки
# стоит пробел.
#
# Пример 1
#   ввод:
#     4075
#   в терминале:
#     Натуральное число: 4075
#     Цифр: 4
# Пример 2
#   ввод:
#     7
#   в терминале:
#     Натуральное число: 7
#     Цифр: 1
# Пример 3
#   ввод:
#     1000000
#   в терминале:
#     Натуральное число: 1000000
#     Цифр: 7

# Решение

natural_number = int(input("Введите натуральное число: "))
saver_number = natural_number

count = 0

while natural_number != 0:
  natural_number = natural_number // 10
  count += 1 

print(f"Натуральное число: {saver_number}")
print(f"Цифр: {count}")
